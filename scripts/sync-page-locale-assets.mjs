// Copies sibling page.html i18n JSON into published LOC locale assets for both Web and
// native IPA exports. Source-of-truth stays beside each page.html, not in public.
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const app=path.join(root,'app');
const target=path.join(root,'public','i18n');
const locales=['zh_tw','zh_cn','en','ja'];

function pageDirs(folder,found=[]){
  for(const entry of fs.readdirSync(folder,{withFileTypes:true})){
    const full=path.join(folder,entry.name);
    if(entry.isFile()&&entry.name==='page.html')found.push(folder);
    else if(entry.isDirectory())pageDirs(full,found);
  }
  return found;
}
function readLocale(source){
  if(!fs.existsSync(source))throw new Error('Missing page locale JSON: '+path.relative(root,source));
  const bytes=fs.readFileSync(source);
  const parsed=JSON.parse(bytes.toString('utf8'));
  if(!parsed||typeof parsed!=='object'||Array.isArray(parsed))
    throw new Error('Invalid locale object: '+path.relative(root,source));
  return {bytes,empty:Object.keys(parsed).length===0};
}
function writeLocale(bytes,destination){
  fs.mkdirSync(path.dirname(destination),{recursive:true});
  fs.writeFileSync(destination,bytes);
}
const pages=pageDirs(app).sort();
if(!pages.length)throw new Error('No page.html routes found');
// Only these two generated namespaces belong to this script. Do not touch
// other public files or another Agent's assets.
for(const suffix of ['pages','shared'])
  fs.rmSync(path.join(target,suffix),{recursive:true,force:true});
function localeSource(dir,locale){
  const route=path.relative(app,dir).replace(/\\/g,'/');
  // LRS owns non-page sources under app/lrunes; these HTML documents
  // reuse their LOC feature route JSON, never a tracked LRS-owned copy.
  const canonical=route==='lrunes'?'':route.startsWith('lrunes/')?route.slice(7):null;
  return canonical===null?path.join(dir,'i18n',locale+'.json')
    :path.join(app,canonical,'i18n',locale+'.json');
}
const emptyPageLocales=[];
const aliases={};
const byContent=new Map();
let published=0;
for(const dir of pages){
  const route=path.relative(app,dir).replace(/\\/g,'/')||'index';
  for(const locale of locales){
    const key=route+'/'+locale;
    const {bytes,empty}=readLocale(localeSource(dir,locale));
    if(empty){emptyPageLocales.push(key);continue;}
    // Hash narrows candidates; byte equality is mandatory before sharing.
    // One published resource serves all routes with identical language copy.
    const digest=locale+':'+createHash('sha256').update(bytes).digest('hex');
    const previous=byContent.get(digest)||[];
    const match=previous.find(item=>item.bytes.equals(bytes));
    if(match){aliases[key]=match.key;continue;}
    previous.push({key,bytes});
    byContent.set(digest,previous);
    writeLocale(bytes,path.join(target,'pages',route,locale+'.json'));
    published++;
  }
}
for(const locale of locales){
  const {bytes,empty}=readLocale(path.join(app,'i18n','shared',locale+'.json'));
  if(empty)throw new Error('Shared locale must not be empty: '+locale);
  writeLocale(bytes,path.join(target,'shared',locale+'.json'));
}
fs.writeFileSync(path.join(app,'i18n','page-locale-manifest.js'),
  '// Generated by sync-page-locale-assets.mjs. Do not edit manually.\n'+
  'export const EMPTY_PAGE_LOCALES = new Set('+JSON.stringify(emptyPageLocales)+');\n'+
  'export const PAGE_LOCALE_ALIASES = Object.freeze('+JSON.stringify(aliases)+');\n','utf8');
console.log('[page-locales] '+pages.length+' routes; '+published+' unique page assets, '+
  Object.keys(aliases).length+' exact duplicates shared, '+emptyPageLocales.length+
  ' empty dictionaries omitted; 4 shared assets.');
