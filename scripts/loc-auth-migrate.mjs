// One-time vendor migration. LOC Auth owns loc_auth, independent of
// website api.manage and Neon-managed neon_auth. Never run at request time.
import assert from 'node:assert/strict';
import {getMigrations} from 'better-auth/db/migration';
import {createLocAuth} from '../workers/loc-authority/auth.mjs';
import {applyLocAuthRls} from './loc-auth-rls.mjs';

if(process.env.LOC_AUTH_APPLY_SCHEMA!=='1')
  throw Error('LOC Auth migration requires explicit LOC_AUTH_APPLY_SCHEMA=1');
if(!process.env.LOC_AUTH_DATABASE_URL)
  throw Error('LOC_AUTH_DATABASE_URL is required in the trusted server environment');
if(!process.env.LOC_AUTH_RLS_ROLE)
  throw Error('LOC_AUTH_RLS_ROLE is required; Auth tables must not deploy without RLS');

// Google credentials are needed at sign-in, not for generating database DDL.
// Do not require a user to configure OAuth in website settings.
const env={...process.env,
  LOC_GOOGLE_CLIENT_ID:process.env.LOC_GOOGLE_CLIENT_ID||
    process.env.GOOGLE_CLIENT_ID||'migration-only-client',
  LOC_GOOGLE_CLIENT_SECRET:process.env.LOC_GOOGLE_CLIENT_SECRET||
    process.env.GOOGLE_CLIENT_SECRET||'migration-only-secret'};
const {auth,pool}=createLocAuth(env);
try{
  const {runMigrations}=await getMigrations(auth.options);
  await runMigrations();
  const required=['user','session','account','verification'];
  const {rows}=await pool.query(
    'SELECT table_name FROM information_schema.tables '+
    'WHERE table_schema=$1 AND table_name=ANY($2::text[])',
    ['loc_auth',required]);
  assert.deepEqual(rows.map(x=>x.table_name).sort(),required.sort(),
    'LOC Auth must have all four Better Auth core tables');
  // Apply role-specific RLS to all core and plugin tables as one transaction.
  // This never creates a role or alters LOC Web / api.manage / neon_auth.
  const covered=await applyLocAuthRls(pool,process.env.LOC_AUTH_RLS_ROLE);
  // Additional JWT and OAuth Provider tables are generated by the same module.
  console.log('LOC Auth RLS enabled + forced for',covered.length,'tables');
  console.log('LOC Auth PostgreSQL schema ready; core tables:',
    rows.map(x=>x.table_name).sort().join(', '));
}finally{
  await pool.end();
}
