// Direct LOC integration of the vendored kysely-codegen 0.20.0 implementation.
// The upstream metadata model, dialect adapters and serializer remain intact;
// this adapter only translates LOC's frozen physical snapshot into their input.
import {createRequire} from 'node:module';
import contract from '../../../zenstack/schema-contract.mjs';

const require=createRequire(new URL('../../../vendor/kysely-codegen/package.json',import.meta.url));
const {DatabaseMetadata}=require('./dist/introspector/metadata/database-metadata.js');
const {TypeScriptSerializer}=require('./dist/generator/generator/serializer.js');
const {PostgresDialect}=require('./dist/generator/dialects/postgres/postgres-dialect.js');
const {MysqlDialect}=require('./dist/generator/dialects/mysql/mysql-dialect.js');
const {MssqlDialect}=require('./dist/generator/dialects/mssql/mssql-dialect.js');

export const LOC_KYSELY_DIALECTS=Object.freeze({
  postgres:PostgresDialect,
  mysql:MysqlDialect,
  mssql:MssqlDialect
});

const asDataType=format=>format.startsWith('_')?format.slice(1):format;

export function locKyselyMetadata(){
  return new DatabaseMetadata({tables:contract.tables.map(table=>({
    name:table.table,
    schema:table.schema||contract.schema,
    columns:table.columns.map(column=>({
      name:column.name,
      dataType:asDataType(column.format),
      isArray:column.format.startsWith('_'),
      isNullable:column.nullable,
      hasDefaultValue:column.hasDefault,
      // LOC's generated flag also covers computed DATE columns. The upstream
      // generator reserves this flag for insert-time identity columns.
      isAutoIncrementing:false,
      comment:null
    }))
  }))});
}

export function generateLocKyselyTypes(dialect='postgres'){
  const Dialect=LOC_KYSELY_DIALECTS[dialect];
  if(!Dialect)throw new Error('Unsupported LOC Kysely codegen dialect');
  return new TypeScriptSerializer({
    skipAutogeneratedFileComment:false,
    typeOnlyImports:true
  }).serializeFile(locKyselyMetadata(),new Dialect());
}
