-- The slowest query on this project (238 calls, 6.16s mean, 14.68s max,
-- 1,467,080ms total -- the #1 entry in pg_stat_statements) is a PostgREST
-- direct-table REST request against silver.lo3rwang_galaxy:
--   WHERE date = ANY($1) ORDER BY uid ASC LIMIT $2 OFFSET $3
-- Confirmed via pg_indexes: this table only had two separate indexes
-- (uid pkey, and date alone). Postgres could use idx_lo3rwang_galaxy_date
-- to find the date-matching rows, but uid is a random 8-char id
-- uncorrelated with date, so it could not also satisfy the ORDER BY from
-- an index -- it had to pull every date-matching row into memory and sort
-- by uid before applying LIMIT/OFFSET. That sort is the entire cost.
-- A composite (date, uid) index lets Postgres satisfy the filter AND the
-- sort from one index scan, eliminating the sort step regardless of who
-- is calling this query. This does not touch any RLS policy, grant, or
-- application code -- it is a pure read-path performance fix.
--
-- Already applied live to project qlouywsdiiyiyzpoxyqy via apply_migration
-- (name: index_galaxy_date_uid_for_pagination) before this file was
-- written -- this is purely for version-control tracking, same as the
-- silver.loc GRANT fix earlier tonight.
CREATE INDEX IF NOT EXISTS idx_lo3rwang_galaxy_date_uid
  ON silver.lo3rwang_galaxy USING btree (date, uid);
